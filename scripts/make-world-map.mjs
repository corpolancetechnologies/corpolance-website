// Generates a dotted world map (public/images/world-dots.svg) and the projected
// coordinates of the regions highlighted in the Global Delivery section
// (src/data/mapPoints.ts). Run with: node scripts/make-world-map.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { feature } from 'topojson-client'
import { geoContains, geoEquirectangular } from 'd3-geo'

const require = createRequire(import.meta.url)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'))
const land = feature(topo, topo.objects.land)

const WIDTH = 1000
const HEIGHT = 470
// Crop Antarctica and the far north; shift the frame so the map is centred.
const projection = geoEquirectangular()
  .scale(WIDTH / (2 * Math.PI))
  .translate([WIDTH / 2, HEIGHT / 2 + 48])

const STEP = 2.2
const dots = []
for (let lat = 80; lat >= -58; lat -= STEP) {
  for (let lon = -180; lon < 180; lon += STEP) {
    if (geoContains(land, [lon, lat])) {
      const [x, y] = projection([lon, lat])
      if (y > 2 && y < HEIGHT - 2) dots.push([x.toFixed(1), y.toFixed(1)])
    }
  }
}

const r = 2.1
const path = dots.map(([x, y]) => `M${x} ${y}m-${r} 0a${r} ${r} 0 1 0 ${r * 2} 0a${r} ${r} 0 1 0 -${r * 2} 0`).join('')
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="${WIDTH}" height="${HEIGHT}"><path fill="#9bbbd3" d="${path}"/></svg>\n`
writeFileSync(resolve(root, 'public/images/world-dots.svg'), svg)

const places = {
  india: [78.5, 21],
  usa: [-98, 39],
  canada: [-100, 56],
  europe: [10, 50],
}
const lines = Object.entries(places).map(([k, ll]) => {
  const [x, y] = projection(ll)
  return `  ${k}: { x: ${x.toFixed(1)}, y: ${y.toFixed(1)} },`
})
writeFileSync(
  resolve(root, 'src/data/mapPoints.ts'),
  `// Generated by scripts/make-world-map.mjs — projected positions on world-dots.svg.\nexport const MAP_SIZE = { width: ${WIDTH}, height: ${HEIGHT} } as const\n\nexport const mapPoints = {\n${lines.join('\n')}\n} as const\n`,
)
console.log(`world map: ${dots.length} dots`)
